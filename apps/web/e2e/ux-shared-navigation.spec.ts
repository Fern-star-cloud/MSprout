import { expect, test, type BrowserContext } from '@playwright/test'
import { churchId, ministryId, json, expectNoSeriousAccessibilityIssues } from './support'

test.use({ serviceWorkers: 'block' })
async function verified(context: BrowserContext, role: 'owner' | 'teacher', name = 'Sample Community Church') {
  await context.route('**/auth/session', route => json(route, { id: 11, email_verified: true, workspaces: [{ church_id: churchId, name, role }] }))
  await context.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (path === '/api/me') return json(route, { id: 11, memberships: [{ church_id: churchId, status: 'active', role }], assignments: { ministry_ids: [ministryId] }, active_session: { mfa_confirmed: true } })
    if (path === '/api/ministries') return json(route, { data: [{ id: ministryId, name: 'Assigned ministry', status: 'active' }] })
    return json(route, { data: [] })
  })
}

test('Owner navigation stays compact after Home, reveals active People children and supports history', async ({ page, context }) => {
  await verified(context, 'owner')
  const writes: string[] = []
  page.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()) })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/account/more')
  await expect(page.getByRole('heading', { name: 'More', exact: true })).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  // More is a device-independent entry; its heading may precede optional online verification.
  await expect(nav.getByRole('link', { name: 'People', exact: true })).toBeVisible()
  expect(await nav.getByRole('link').allTextContents()).toEqual(['Home', 'Attendance', 'People', 'Review', 'Reports & history', 'Birthdays', 'Activity', 'Sync & device', 'Account'])
  const toggle = nav.getByRole('button', { name: 'Show People destinations' })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  const controlled = await toggle.getAttribute('aria-controls')
  expect(await page.evaluate(id => !!document.getElementById(id!)?.hidden, controlled)).toBe(true)
  await toggle.focus(); await page.keyboard.press('Enter')
  await nav.getByRole('link', { name: 'Students', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Students', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Students', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(nav.getByRole('link', { name: 'People', exact: true })).toHaveAttribute('aria-current', 'location')
  await toggle.focus(); await page.keyboard.press('Space')
  await expect(nav.getByRole('link', { name: 'Students', exact: true })).toBeHidden()
  await expect(nav.getByRole('link', { name: 'People', exact: true })).toHaveAttribute('aria-current', 'location')
  expect(await nav.getByRole('link', { name: 'People', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(212, 232, 255)')
  expect(await page.locator('.wide-layout').evaluate(el => getComputedStyle(el).backgroundImage)).toContain('linear-gradient')
  await nav.getByRole('link', { name: 'Home', exact: true }).click()
  await page.goBack(); await expect(page.getByRole('heading', { name: 'Students', exact: true })).toBeVisible()
  // Back preserves the user's explicit collapse choice for this destination.
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(nav.getByRole('link', { name: 'People', exact: true })).toHaveAttribute('aria-current', 'location')
  await page.goForward(); await expect(page.getByRole('heading', { name: 'Home', exact: true })).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await nav.getByRole('link', { name: 'Attendance', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Unlock an existing device profile' })).toBeVisible()
  expect(writes).toEqual([])
  await expectNoSeriousAccessibilityIssues(page)
})

for (const role of ['owner', 'teacher'] as const) {
  test(`${role} phone More preserves short Account/Sync paths, active parents and truthful state`, async ({ page, context }) => {
    await verified(context, role)
    await page.setViewportSize({ width: 390, height: 900 })
    await page.goto('/account/home')
    await expect(page.getByRole('heading', { name: 'Home', exact: true })).toBeVisible()
    const phone = page.getByRole('navigation', { name: 'Phone navigation' })
    expect(await phone.getByRole('link').allTextContents()).toEqual(role === 'owner' ? ['Home', 'Attendance', 'Review', 'People', 'More'] : ['Home', 'Attendance', 'Sync', 'More'])
    if (role === 'owner') await expect(page.locator('.protected-sync-link')).toBeVisible()
    await phone.getByRole('link', { name: 'More', exact: true }).click()
    const more = page.getByRole('navigation', { name: 'More destinations' })
    await expect(more).toBeVisible()
    if (role === 'teacher') {
      expect((await more.getByRole('link').allTextContents()).slice(0, 5)).toEqual(['My ministries›', 'Recent sessions›', 'Birthdays›', 'My activity›', 'Account›'])
      for (const label of ['Teachers', 'Import', 'People', 'Review']) await expect(page.getByRole('link', { name: label, exact: true })).toHaveCount(0)
    }
    await expect(phone.getByRole('link', { name: 'More', exact: true })).toHaveAttribute('aria-current', 'page')
    await expectNoSeriousAccessibilityIssues(page)
    await more.getByRole('link', { name: 'Account', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Account', exact: true })).toBeVisible()
    await page.goBack(); await expect(more).toBeVisible()
    await more.getByRole('link', { name: 'Sync & device', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Sync & device', exact: true })).toBeVisible()
    if (role === 'teacher') await expect(phone.getByRole('link', { name: 'Sync', exact: true })).toHaveAttribute('aria-current', 'page')
    else await expect(page.locator('.protected-sync-link')).toHaveAttribute('aria-current', 'page')
    expect(await phone.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expectNoSeriousAccessibilityIssues(page)
  })

  test(`${role} tablet drawer contains focus, groups People, closes on escape/navigation/transition`, async ({ page, context }) => {
    await verified(context, role)
    await page.setViewportSize({ width: 800, height: 900 })
    await page.goto('/account/more')
    await expect(page.getByRole('heading', { name: 'More', exact: true })).toBeVisible()
    const menu = page.getByRole('button', { name: 'Menu', exact: true })
    await menu.focus(); await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Navigation', exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Close navigation' })).toBeFocused()
    for (let index = 0; index < 16; index++) { await page.keyboard.press(index % 2 ? 'Shift+Tab' : 'Tab'); expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true) }
    const nav = dialog.getByRole('navigation', { name: 'Tablet navigation' })
    if (role === 'owner') {
      const toggle = nav.getByRole('button', { name: 'Show People destinations' })
      await expect(toggle).toHaveAttribute('aria-expanded', 'false')
      await toggle.click(); await expect(nav.getByRole('link', { name: 'Import', exact: true })).toBeVisible()
    } else await expect(nav.getByRole('link', { name: 'People', exact: true })).toHaveCount(0)
    await expectNoSeriousAccessibilityIssues(page)
    await page.keyboard.press('Escape'); await expect(menu).toBeFocused()
    await menu.click(); await nav.getByRole('link', { name: 'Home', exact: true }).click()
    await expect(dialog).toBeHidden(); await expect(page.getByRole('main')).toBeFocused()
    await menu.click(); await dialog.getByRole('link', { name: 'MSprout home', exact: true }).click()
    await expect(dialog).toBeHidden(); await expect(menu).toBeFocused()
    await menu.click(); await page.setViewportSize({ width: 1024, height: 900 }); await expect(dialog).toBeHidden()
    await expect(page.getByRole('main')).toBeFocused()
    await page.setViewportSize({ width: 800, height: 900 }); await menu.click()
    await page.setViewportSize({ width: 390, height: 900 }); await expect(dialog).toBeHidden()
    await expect(page.getByRole('navigation', { name: 'Phone navigation' })).toBeVisible()
  })
}

test('compact names, More and active bars reflow with enlarged text and system colors', async ({ page, context }) => {
  const name = 'W'.repeat(160)
  await verified(context, 'owner', name)
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 }); await page.goto('/account/more')
    await expect(page.getByRole('heading', { name: 'More', exact: true })).toBeVisible()
    const summary = page.locator('.church-name-details summary')
    expect((await summary.locator('.compact-text > span[aria-hidden]').textContent())?.length).toBe(50)
    await summary.focus(); await page.keyboard.press('Enter')
    await expect(page.locator('.church-name-expanded')).toHaveText(name)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.keyboard.press('Enter'); await expectNoSeriousAccessibilityIssues(page)
  }
  await page.setViewportSize({ width: 320, height: 900 }); await page.addStyleTag({ content: ':root { font-size: 200%; }' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await page.locator('.church-name-details summary').boundingBox())!.width).toBeGreaterThanOrEqual(44)
  const last = page.getByRole('navigation', { name: 'More destinations' }).getByRole('link', { name: 'Account', exact: true })
  await last.focus(); await last.scrollIntoViewIfNeeded()
  expect((await last.boundingBox())!.y + (await last.boundingBox())!.height).toBeLessThanOrEqual((await page.getByRole('navigation', { name: 'Phone navigation' }).boundingBox())!.y)
  await expectNoSeriousAccessibilityIssues(page)
  await page.emulateMedia({ reducedMotion: 'reduce', forcedColors: 'active' }); await expectNoSeriousAccessibilityIssues(page)
})

test('Teacher direct Owner destinations fail closed and offline navigation exposes no inferred role', async ({ page, context }) => {
  await verified(context, 'teacher')
  await page.goto('/account/teachers')
  await expect(page.getByText(/This destination is available to the church Owner/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'Teachers', exact: true })).toHaveCount(0)
  await page.goto('/account/imports')
  await expect(page.getByText(/Student imports are available only to the church Owner/)).toBeVisible()
  await expect(page.getByLabel('Student spreadsheet')).toHaveCount(0)
  await page.goto('/attendance'); await expect(page.getByRole('heading', { name: 'Take attendance' })).toBeVisible()
  await context.setOffline(true); await page.evaluate(() => window.dispatchEvent(new Event('offline')))
  await expect(page.getByText('Teacher', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'People', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Take attendance' })).toBeVisible()
  await page.setViewportSize({ width: 320, height: 900 })
  await page.addStyleTag({ content: ':root { font-size: 200%; }' })
  expect(await page.locator('.workspace-header').evaluate(el => el.getBoundingClientRect().height)).toBeLessThan(200)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
